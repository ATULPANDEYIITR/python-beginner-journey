BEGIN;

CREATE SCHEMA IF NOT EXISTS repo_practice;
SET search_path TO repo_practice, public;

-- Stable repository identity and branch-level governance are separate records.
CREATE TABLE IF NOT EXISTS repositories (
    repository_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    default_branch TEXT NOT NULL DEFAULT 'main',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (name ~ '^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$')
);

CREATE TABLE IF NOT EXISTS repository_members (
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    username TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('read', 'write', 'maintain', 'admin')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (repository_id, username)
);

CREATE TABLE IF NOT EXISTS branches (
    branch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    name TEXT NOT NULL,
    head_sha TEXT,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (repository_id, name),
    CHECK (name <> ''),
    CHECK (head_sha IS NULL OR head_sha ~ '^[a-f0-9]{7,64}$')
);

CREATE TABLE IF NOT EXISTS commits (
    commit_sha TEXT PRIMARY KEY CHECK (commit_sha ~ '^[a-f0-9]{7,64}$'),
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    parent_sha TEXT,
    author TEXT NOT NULL,
    message TEXT NOT NULL CHECK (message <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (repository_id, commit_sha),
    FOREIGN KEY (repository_id, parent_sha)
        REFERENCES commits(repository_id, commit_sha)
        DEFERRABLE INITIALLY DEFERRED
);

ALTER TABLE branches
    DROP CONSTRAINT IF EXISTS branches_head_fk;

ALTER TABLE branches
    ADD CONSTRAINT branches_head_fk
    FOREIGN KEY (repository_id, head_sha)
    REFERENCES commits(repository_id, commit_sha)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE IF NOT EXISTS pull_requests (
    pr_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    pr_number INTEGER NOT NULL CHECK (pr_number > 0),
    title TEXT NOT NULL CHECK (title <> ''),
    author TEXT NOT NULL,
    source_branch_id BIGINT NOT NULL REFERENCES branches(branch_id),
    target_branch_id BIGINT NOT NULL REFERENCES branches(branch_id),
    state TEXT NOT NULL DEFAULT 'open'
        CHECK (state IN ('draft', 'open', 'merged', 'closed')),
    merge_strategy TEXT NOT NULL DEFAULT 'squash'
        CHECK (merge_strategy IN ('merge', 'squash', 'rebase')),
    head_sha TEXT,
    base_sha TEXT,
    merged_sha TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (repository_id, pr_number),
    CHECK (source_branch_id <> target_branch_id),
    CHECK (
        (state = 'merged' AND merged_sha IS NOT NULL)
        OR (state <> 'merged' AND merged_sha IS NULL)
    ),
    FOREIGN KEY (repository_id, head_sha)
        REFERENCES commits(repository_id, commit_sha)
        DEFERRABLE INITIALLY DEFERRED,
    FOREIGN KEY (repository_id, base_sha)
        REFERENCES commits(repository_id, commit_sha)
        DEFERRABLE INITIALLY DEFERRED,
    FOREIGN KEY (repository_id, merged_sha)
        REFERENCES commits(repository_id, commit_sha)
        DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS pull_request_commits (
    pr_id BIGINT NOT NULL REFERENCES pull_requests(pr_id) ON DELETE CASCADE,
    commit_sha TEXT NOT NULL REFERENCES commits(commit_sha),
    ordinal INTEGER NOT NULL CHECK (ordinal > 0),
    PRIMARY KEY (pr_id, commit_sha),
    UNIQUE (pr_id, ordinal)
);

CREATE TABLE IF NOT EXISTS review_requests (
    pr_id BIGINT NOT NULL REFERENCES pull_requests(pr_id) ON DELETE CASCADE,
    reviewer TEXT NOT NULL,
    requested_by TEXT NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (pr_id, reviewer)
);

CREATE TABLE IF NOT EXISTS reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pr_id BIGINT NOT NULL REFERENCES pull_requests(pr_id) ON DELETE CASCADE,
    reviewer TEXT NOT NULL,
    state TEXT NOT NULL CHECK (
        state IN ('commented', 'approved', 'changes_requested', 'dismissed')
    ),
    reviewed_head_sha TEXT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    dismissed_at TIMESTAMPTZ,
    FOREIGN KEY (pr_id, reviewer)
        REFERENCES review_requests(pr_id, reviewer) ON DELETE CASCADE,
    CHECK (
        (state = 'dismissed' AND dismissed_at IS NOT NULL)
        OR (state <> 'dismissed' AND dismissed_at IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS review_comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES reviews(review_id) ON DELETE CASCADE,
    file_path TEXT NOT NULL CHECK (file_path <> ''),
    line_number INTEGER CHECK (line_number IS NULL OR line_number > 0),
    body TEXT NOT NULL CHECK (body <> ''),
    resolved BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at TIMESTAMPTZ,
    CHECK (
        (resolved AND resolved_at IS NOT NULL)
        OR (NOT resolved AND resolved_at IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS status_checks (
    check_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pr_id BIGINT NOT NULL REFERENCES pull_requests(pr_id) ON DELETE CASCADE,
    check_name TEXT NOT NULL CHECK (check_name <> ''),
    status TEXT NOT NULL CHECK (status IN ('pending', 'success', 'failure')),
    checked_head_sha TEXT NOT NULL,
    completed_at TIMESTAMPTZ,
    UNIQUE (pr_id, check_name),
    CHECK (
        (status = 'pending' AND completed_at IS NULL)
        OR (status <> 'pending' AND completed_at IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS branch_protection (
    protection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL UNIQUE REFERENCES branches(branch_id)
        ON DELETE CASCADE,
    required_approvals INTEGER NOT NULL DEFAULT 2 CHECK (required_approvals >= 0),
    require_resolved_conversations BOOLEAN NOT NULL DEFAULT TRUE,
    require_linear_history BOOLEAN NOT NULL DEFAULT TRUE,
    restrict_direct_push BOOLEAN NOT NULL DEFAULT TRUE,
    allow_force_push BOOLEAN NOT NULL DEFAULT FALSE,
    allow_deletion BOOLEAN NOT NULL DEFAULT FALSE,
    allow_admin_bypass BOOLEAN NOT NULL DEFAULT FALSE,
    require_signed_commits BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS required_status_checks (
    protection_id BIGINT NOT NULL REFERENCES branch_protection(protection_id)
        ON DELETE CASCADE,
    check_name TEXT NOT NULL CHECK (check_name <> ''),
    PRIMARY KEY (protection_id, check_name)
);

CREATE TABLE IF NOT EXISTS merge_eligibility_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pr_id BIGINT NOT NULL REFERENCES pull_requests(pr_id) ON DELETE CASCADE,
    eligible BOOLEAN NOT NULL,
    blockers TEXT[] NOT NULL DEFAULT '{}',
    evaluated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_pr_target_state
    ON pull_requests(target_branch_id, state);

CREATE INDEX IF NOT EXISTS idx_reviews_pr_reviewer_time
    ON reviews(pr_id, reviewer, submitted_at DESC, review_id DESC);

CREATE INDEX IF NOT EXISTS idx_comments_unresolved
    ON review_comments(review_id) WHERE resolved = FALSE;

CREATE INDEX IF NOT EXISTS idx_checks_pr_head
    ON status_checks(pr_id, checked_head_sha, check_name);

CREATE OR REPLACE FUNCTION enforce_pull_request_integrity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    source_repository BIGINT;
    target_repository BIGINT;
BEGIN
    SELECT repository_id INTO source_repository
    FROM branches WHERE branch_id = NEW.source_branch_id;

    SELECT repository_id INTO target_repository
    FROM branches WHERE branch_id = NEW.target_branch_id;

    IF source_repository IS NULL OR target_repository IS NULL THEN
        RAISE EXCEPTION 'Source and target branches must exist';
    END IF;

    IF source_repository <> NEW.repository_id
       OR target_repository <> NEW.repository_id THEN
        RAISE EXCEPTION 'Pull request branches must belong to its repository';
    END IF;

    IF NEW.source_branch_id = NEW.target_branch_id THEN
        RAISE EXCEPTION 'Source and target branches must differ';
    END IF;

    IF NEW.author IS NULL OR btrim(NEW.author) = '' THEN
        RAISE EXCEPTION 'Pull request author is required';
    END IF;

    IF TG_OP = 'UPDATE' AND OLD.state = 'merged'
       AND NEW.state <> 'merged' THEN
        RAISE EXCEPTION 'Merged pull requests cannot be reopened or closed';
    END IF;

    IF TG_OP = 'UPDATE' AND OLD.state = 'closed'
       AND NEW.state NOT IN ('closed', 'open') THEN
        RAISE EXCEPTION 'Closed pull requests may only remain closed or reopen';
    END IF;

    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_pr_integrity ON pull_requests;
CREATE TRIGGER trg_pr_integrity
BEFORE INSERT OR UPDATE ON pull_requests
FOR EACH ROW EXECUTE FUNCTION enforce_pull_request_integrity();

CREATE OR REPLACE FUNCTION enforce_review_eligibility()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    pr_author TEXT;
    current_head TEXT;
    pr_state TEXT;
    member_active BOOLEAN;
    member_role TEXT;
BEGIN
    SELECT author, head_sha, state
    INTO pr_author, current_head, pr_state
    FROM pull_requests WHERE pr_id = NEW.pr_id;

    IF NOT FOUND OR pr_state <> 'open' THEN
        RAISE EXCEPTION 'Reviews require an open pull request';
    END IF;

    IF NEW.reviewer = pr_author THEN
        RAISE EXCEPTION 'Authors cannot review their own pull requests';
    END IF;

    SELECT active, role INTO member_active, member_role
    FROM repository_members rm
    JOIN pull_requests pr USING (repository_id)
    WHERE pr.pr_id = NEW.pr_id AND rm.username = NEW.reviewer;

    IF NOT FOUND OR NOT member_active OR member_role NOT IN ('write', 'maintain', 'admin') THEN
        RAISE EXCEPTION 'Reviewer is not an active eligible repository member';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM review_requests
        WHERE pr_id = NEW.pr_id AND reviewer = NEW.reviewer
    ) THEN
        RAISE EXCEPTION 'Reviewer must be explicitly requested';
    END IF;

    IF NEW.reviewed_head_sha <> current_head THEN
        RAISE EXCEPTION 'Review must reference the current pull request head';
    END IF;

    IF NEW.state = 'dismissed' AND NEW.dismissed_at IS NULL THEN
        RAISE EXCEPTION 'Dismissed reviews require dismissed_at';
    END IF;

    IF NEW.state <> 'dismissed' AND NEW.dismissed_at IS NOT NULL THEN
        RAISE EXCEPTION 'Only dismissed reviews may have dismissed_at';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_review_eligibility ON reviews;
CREATE TRIGGER trg_review_eligibility
BEFORE INSERT OR UPDATE ON reviews
FOR EACH ROW EXECUTE FUNCTION enforce_review_eligibility();

CREATE OR REPLACE FUNCTION enforce_status_check_head()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    current_head TEXT;
    pr_state TEXT;
BEGIN
    SELECT head_sha, state INTO current_head, pr_state
    FROM pull_requests WHERE pr_id = NEW.pr_id;

    IF NOT FOUND OR pr_state <> 'open' THEN
        RAISE EXCEPTION 'Status checks require an open pull request';
    END IF;

    IF NEW.checked_head_sha <> current_head THEN
        RAISE EXCEPTION 'Status check must target the current pull request head';
    END IF;

    IF NEW.status = 'pending' AND NEW.completed_at IS NOT NULL THEN
        RAISE EXCEPTION 'Pending checks cannot have completed_at';
    END IF;

    IF NEW.status <> 'pending' AND NEW.completed_at IS NULL THEN
        NEW.completed_at := now();
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_check_head ON status_checks;
CREATE TRIGGER trg_check_head
BEFORE INSERT OR UPDATE ON status_checks
FOR EACH ROW EXECUTE FUNCTION enforce_status_check_head();

CREATE OR REPLACE FUNCTION evaluate_merge_eligibility(p_pr_id BIGINT)
RETURNS TABLE (eligible BOOLEAN, blockers TEXT[])
LANGUAGE plpgsql
AS $$
DECLARE
    pr RECORD;
    protection RECORD;
    approval_count INTEGER;
    unresolved_count BIGINT;
    failures TEXT[] := '{}';
    required_check RECORD;
    check_record RECORD;
BEGIN
    SELECT p.*, src.head_sha AS actual_head, tgt.head_sha AS actual_base,
           src.is_deleted AS source_deleted, tgt.is_deleted AS target_deleted
    INTO pr
    FROM pull_requests p
    JOIN branches src ON src.branch_id = p.source_branch_id
    JOIN branches tgt ON tgt.branch_id = p.target_branch_id
    WHERE p.pr_id = p_pr_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Pull request % does not exist', p_pr_id;
    END IF;

    IF pr.state <> 'open' THEN
        failures := array_append(failures, 'Pull request is not open');
    END IF;

    IF pr.source_deleted OR pr.target_deleted THEN
        failures := array_append(failures, 'Source or target branch is deleted');
    END IF;

    IF pr.head_sha IS NULL OR pr.head_sha <> pr.actual_head THEN
        failures := array_append(failures, 'Source head is missing or stale');
    END IF;

    IF pr.base_sha IS DISTINCT FROM pr.actual_base THEN
        failures := array_append(failures, 'Target base is stale');
    END IF;

    SELECT bp.* INTO protection
    FROM branch_protection bp
    WHERE bp.branch_id = pr.target_branch_id;

    IF NOT FOUND THEN
        failures := array_append(failures, 'Target branch has no protection policy');
        RETURN QUERY SELECT FALSE, failures;
        RETURN;
    END IF;

    -- Select each reviewer's latest decision, then count only current approvals.
    SELECT count(*) INTO approval_count
    FROM (
        SELECT DISTINCT ON (r.reviewer) r.reviewer, r.state, r.reviewed_head_sha
        FROM reviews r
        WHERE r.pr_id = p_pr_id
        ORDER BY r.reviewer, r.submitted_at DESC, r.review_id DESC
    ) latest
    JOIN repository_members rm
      ON rm.username = latest.reviewer
     AND rm.repository_id = pr.repository_id
     AND rm.active
     AND rm.role IN ('write', 'maintain', 'admin')
    WHERE latest.state = 'approved'
      AND latest.reviewed_head_sha = pr.head_sha
      AND latest.reviewer <> pr.author;

    IF approval_count < protection.required_approvals THEN
        failures := array_append(
            failures,
            format('Insufficient approvals: %s/%s',
                   approval_count, protection.required_approvals)
        );
    END IF;

    FOR required_check IN
        SELECT check_name FROM required_status_checks
        WHERE protection_id = protection.protection_id
    LOOP
        SELECT * INTO check_record
        FROM status_checks sc
        WHERE sc.pr_id = p_pr_id
          AND sc.check_name = required_check.check_name;

        IF NOT FOUND
           OR check_record.status <> 'success'
           OR check_record.checked_head_sha IS DISTINCT FROM pr.head_sha THEN
            failures := array_append(
                failures,
                'Required check missing, failing, pending, or stale: '
                || required_check.check_name
            );
        END IF;
    END LOOP;

    IF protection.require_resolved_conversations THEN
        SELECT count(*) INTO unresolved_count
        FROM review_comments rc
        JOIN reviews r USING (review_id)
        WHERE r.pr_id = p_pr_id AND NOT rc.resolved;

        IF unresolved_count > 0 THEN
            failures := array_append(
                failures,
                format('%s unresolved review comment(s)', unresolved_count)
            );
        END IF;
    END IF;

    IF protection.require_linear_history AND pr.merge_strategy = 'merge' THEN
        failures := array_append(failures, 'Merge commits violate linear-history policy');
    END IF;

    RETURN QUERY SELECT cardinality(failures) = 0, failures;
END;
$$;

CREATE OR REPLACE FUNCTION record_merge_eligibility()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    result RECORD;
BEGIN
    IF NEW.state = 'open' THEN
        SELECT * INTO result FROM evaluate_merge_eligibility(NEW.pr_id);
        INSERT INTO merge_eligibility_audit(pr_id, eligible, blockers)
        VALUES (NEW.pr_id, result.eligible, result.blockers);
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_record_merge_eligibility ON pull_requests;
CREATE TRIGGER trg_record_merge_eligibility
AFTER INSERT OR UPDATE OF state, head_sha, base_sha ON pull_requests
FOR EACH ROW EXECUTE FUNCTION record_merge_eligibility();

-- The merge function serializes the final policy check and branch update.
CREATE OR REPLACE FUNCTION merge_pull_request(p_pr_id BIGINT, p_actor TEXT)
RETURNS TEXT
LANGUAGE plpgsql
AS $$
DECLARE
    pr RECORD;
    protection RECORD;
    result RECORD;
    new_sha TEXT;
BEGIN
    SELECT p.*, tgt.head_sha AS actual_base
    INTO pr
    FROM pull_requests p
    JOIN branches tgt ON tgt.branch_id = p.target_branch_id
    WHERE p.pr_id = p_pr_id
    FOR UPDATE OF p, tgt;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Pull request does not exist';
    END IF;

    IF pr.state <> 'open' THEN
        RAISE EXCEPTION 'Only open pull requests can merge';
    END IF;

    IF pr.author = p_actor THEN
        -- Authors may merge only if repository membership and branch policy permit.
        NULL;
    END IF;

    SELECT bp.* INTO protection
    FROM branch_protection bp
    WHERE bp.branch_id = pr.target_branch_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Branch protection policy is missing';
    END IF;

    SELECT * INTO result FROM evaluate_merge_eligibility(p_pr_id);
    IF NOT result.eligible THEN
        RAISE EXCEPTION 'Merge blocked: %', array_to_string(result.blockers, '; ');
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM repository_members rm
        WHERE rm.repository_id = pr.repository_id
          AND rm.username = p_actor
          AND rm.active
          AND rm.role IN ('write', 'maintain', 'admin')
    ) THEN
        RAISE EXCEPTION 'Actor is not authorized to merge';
    END IF;

    new_sha := substr(md5(
        pr.repository_id::TEXT || ':' || pr.pr_number::TEXT || ':' ||
        pr.head_sha || ':' || clock_timestamp()::TEXT
    ), 1, 12);

    INSERT INTO commits(commit_sha, repository_id, parent_sha, author, message)
    VALUES (
        new_sha, pr.repository_id, pr.actual_base, p_actor,
        'Merge pull request #' || pr.pr_number || ' using ' || pr.merge_strategy
    );

    UPDATE branches SET head_sha = new_sha
    WHERE branch_id = pr.target_branch_id;

    UPDATE pull_requests
    SET state = 'merged', merged_sha = new_sha, updated_at = now()
    WHERE pr_id = p_pr_id;

    RETURN new_sha;
END;
$$;

