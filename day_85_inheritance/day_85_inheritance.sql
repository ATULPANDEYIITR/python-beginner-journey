-- 14. VALIDATION AND RETRIEVAL
-- ------------------------------------------------------------

-- All employees and their calculated salaries.
SELECT *
FROM employee_salary_details
ORDER BY employee_id;

-- Permanent employees.
SELECT
    e.employee_id,
    e.employee_name,
    p.monthly_salary,
    p.annual_bonus
FROM employees e
JOIN permanent_employees p
    ON p.employee_id = e.employee_id
ORDER BY e.employee_id;

-- Senior employees.
SELECT
    e.employee_name,
    p.monthly_salary,
    s.leadership_allowance
FROM employees e
JOIN permanent_employees p
    ON p.employee_id = e.employee_id
JOIN senior_employees s
    ON s.employee_id = e.employee_id;

-- Employees grouped by employment type.
SELECT
    employment_type,
    COUNT(*) AS employee_count
FROM employees
GROUP BY employment_type
ORDER BY employment_type;

-- Department payroll aggregation.
SELECT
    department,
    ROUND(
        SUM(gross_monthly_salary),
        2
    ) AS department_payroll
FROM employee_salary_details
WHERE status = 'ACTIVE'
GROUP BY department
ORDER BY department;

-- ------------------------------------------------------------
-- 15. ELIGIBILITY EVALUATION
-- ------------------------------------------------------------

CREATE OR REPLACE VIEW payroll_eligibility AS
SELECT
    e.employee_id,
    e.employee_name,
    e.status,
    CASE
        WHEN e.status <> 'ACTIVE'
            THEN FALSE

        WHEN e.employment_type = 'PERMANENT'
            AND EXISTS (
                SELECT 1
                FROM permanent_employees p
                WHERE p.employee_id = e.employee_id
            )
            THEN TRUE

        WHEN e.employment_type = 'CONTRACT'
            AND EXISTS (
                SELECT 1
                FROM contract_employees c
                WHERE c.employee_id = e.employee_id
            )
            THEN TRUE

        WHEN e.employment_type = 'INTERN'
            AND EXISTS (
                SELECT 1
                FROM intern_employees i
                WHERE i.employee_id = e.employee_id
            )
            THEN TRUE

        ELSE FALSE
    END AS eligible
FROM employees e;

SELECT *
FROM payroll_eligibility
ORDER BY employee_id;

-- ------------------------------------------------------------
-- 16. PROCESSING WORKFLOW
-- ------------------------------------------------------------

-- Process all eligible employees in one transaction.
DO $$
DECLARE
    employee_record RECORD;
    payroll_reference BIGINT;
BEGIN
    FOR employee_record IN
        SELECT employee_id
        FROM payroll_eligibility
        WHERE eligible = TRUE
        ORDER BY employee_id
    LOOP
        payroll_reference :=
            process_employee_payroll(
                employee_record.employee_id
            );

        RAISE NOTICE
            'Employee % processed. Payroll ID %',
            employee_record.employee_id,
            payroll_reference;
    END LOOP;
END;
$$;

-- ------------------------------------------------------------
-- 17. PAYROLL REPORTING
-- ------------------------------------------------------------

SELECT
    e.employee_name,
    e.department,
    p.gross_salary,
    p.deductions,
    p.net_salary,
    p.status,
    p.processed_at
FROM payroll_runs p
JOIN employees e
    ON e.employee_id = p.employee_id
ORDER BY p.payroll_id;

-- Total processed payroll.
SELECT
    COUNT(*) AS processed_records,
    SUM(gross_salary) AS total_gross,
    SUM(deductions) AS total_deductions,
    SUM(net_salary) AS total_net
FROM payroll_runs
WHERE status = 'PROCESSED';

-- ------------------------------------------------------------
-- 18. CTE-BASED PAYROLL ANALYSIS
-- ------------------------------------------------------------

WITH department_payroll AS (
    SELECT
        e.department,
        COUNT(*) AS employee_count,
        SUM(r.gross_salary) AS gross_total,
        SUM(r.net_salary) AS net_total
    FROM payroll_runs r
    JOIN employees e
        ON e.employee_id = r.employee_id
    WHERE r.status = 'PROCESSED'
    GROUP BY e.department
)
SELECT
    department,
    employee_count,
    gross_total,
    net_total,
    ROUND(
        gross_total / NULLIF(employee_count, 0),
        2
    ) AS average_gross_salary
FROM department_payroll
ORDER BY gross_total DESC;

