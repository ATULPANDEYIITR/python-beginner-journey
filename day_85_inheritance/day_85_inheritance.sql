-- 20. TRANSACTION AND ROLLBACK EXAMPLE
-- ------------------------------------------------------------

-- A failed business operation can be rolled back without
-- leaving a partially inserted payroll transaction.

SAVEPOINT payroll_checkpoint;

DO $$
BEGIN
    BEGIN
        INSERT INTO payroll_runs (
            employee_id,
            policy_id,
            gross_salary,
            deductions,
            net_salary,
            status
        )
        SELECT
            101,
            policy_id,
            10000,
            1200,
            8800,
            'PENDING'
        FROM payroll_policies
        WHERE active = TRUE;

        -- The savepoint remains available to the caller.
        RAISE NOTICE 'Example pending payroll record created';

    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'Payroll operation failed: %', SQLERRM;
        RAISE;
    END;
END;
$$;

ROLLBACK TO SAVEPOINT payroll_checkpoint;

RELEASE SAVEPOINT payroll_checkpoint;

