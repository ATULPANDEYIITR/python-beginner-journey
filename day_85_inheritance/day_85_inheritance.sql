-- ============================================================
-- POSTGRESQL INHERITANCE AND EMPLOYEE PAYROLL
-- ============================================================
--
-- This implementation demonstrates relational representation
-- of object-oriented inheritance using table-per-type mapping.
--
-- PostgreSQL table inheritance is different from Python class
-- inheritance. This script uses explicit primary keys and
-- foreign keys for reliable relational integrity.
--
-- Domain:
-- Employee
--   |
--   +-- Permanent Employee
--   |      |
--   |      +-- Senior Employee
--   |
--   +-- Contract Employee
--   |
--   +-- Intern Employee
--
-- ============================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS payroll;

SET search_path TO payroll, public;

-- ------------------------------------------------------------
-- 1. ENUMERATED DOMAIN TYPES
-- ------------------------------------------------------------

CREATE TYPE employment_type AS ENUM (
    'PERMANENT',
    'CONTRACT',
    'INTERN'
);

CREATE TYPE employee_status AS ENUM (
    'ACTIVE',
    'INACTIVE'
);

CREATE TYPE payroll_status AS ENUM (
    'PENDING',
    'PROCESSED',
    'FAILED'
);

-- ------------------------------------------------------------
-- 2. BASE EMPLOYEE TABLE
-- ------------------------------------------------------------

CREATE TABLE employees (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    employee_name VARCHAR(120) NOT NULL,

    department VARCHAR(100) NOT NULL,

    employment_type employment_type NOT NULL,

    status employee_status NOT NULL DEFAULT 'ACTIVE',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT employee_name_not_empty
        CHECK (length(trim(employee_name)) > 0),

    CONSTRAINT employee_department_not_empty
        CHECK (length(trim(department)) > 0)
);

CREATE INDEX idx_employee_department
    ON employees(department);

CREATE INDEX idx_employee_active
    ON employees(status, employee_id);

-- ------------------------------------------------------------
-- 3. PERMANENT EMPLOYEE SUBTYPE
-- ------------------------------------------------------------

CREATE TABLE permanent_employees (
    employee_id BIGINT PRIMARY KEY,

    monthly_salary NUMERIC(14,2) NOT NULL,

    annual_bonus NUMERIC(14,2) NOT NULL DEFAULT 0,

    CONSTRAINT permanent_employee_parent_fk
        FOREIGN KEY (employee_id)
        REFERENCES employees(employee_id)
        ON DELETE CASCADE,

    CONSTRAINT permanent_salary_nonnegative
        CHECK (monthly_salary >= 0),

    CONSTRAINT permanent_bonus_nonnegative
        CHECK (annual_bonus >= 0)
);

-- ------------------------------------------------------------
-- 4. SENIOR EMPLOYEE SUBTYPE
-- ------------------------------------------------------------

CREATE TABLE senior_employees (
    employee_id BIGINT PRIMARY KEY,

    leadership_allowance NUMERIC(14,2)
        NOT NULL DEFAULT 0,

    CONSTRAINT senior_permanent_parent_fk
        FOREIGN KEY (employee_id)
        REFERENCES permanent_employees(employee_id)
        ON DELETE CASCADE,

    CONSTRAINT senior_allowance_nonnegative
        CHECK (leadership_allowance >= 0)
);

-- ------------------------------------------------------------
-- 5. CONTRACT EMPLOYEE SUBTYPE
-- ------------------------------------------------------------

CREATE TABLE contract_employees (
    employee_id BIGINT PRIMARY KEY,

    hourly_rate NUMERIC(12,2) NOT NULL,

    monthly_hours NUMERIC(7,2) NOT NULL,

    CONSTRAINT contract_employee_parent_fk
        FOREIGN KEY (employee_id)
        REFERENCES employees(employee_id)
        ON DELETE CASCADE,

    CONSTRAINT contract_rate_nonnegative
        CHECK (hourly_rate >= 0),

    CONSTRAINT contract_hours_valid
        CHECK (monthly_hours BETWEEN 0 AND 744)
);

-- ------------------------------------------------------------
-- 6. INTERN EMPLOYEE SUBTYPE
-- ------------------------------------------------------------

CREATE TABLE intern_employees (
    employee_id BIGINT PRIMARY KEY,

    monthly_stipend NUMERIC(14,2) NOT NULL,

    CONSTRAINT intern_employee_parent_fk
        FOREIGN KEY (employee_id)
        REFERENCES employees(employee_id)
        ON DELETE CASCADE,

    CONSTRAINT intern_stipend_nonnegative
        CHECK (monthly_stipend >= 0)
);

-- ------------------------------------------------------------
-- 7. INHERITANCE INTEGRITY TRIGGER
-- ------------------------------------------------------------
--
-- A foreign key guarantees that a subtype has a base employee.
-- The trigger guarantees that the declared employment type
-- matches the subtype table.
--
-- A deferred constraint trigger permits inserting the base
-- employee and its subtype within the same transaction.
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION validate_employee_subtype()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    expected_type employment_type;
    actual_type employment_type;
    parent_id BIGINT;
    subtype_count INTEGER;
BEGIN
    parent_id := COALESCE(NEW.employee_id, OLD.employee_id);

    SELECT employment_type
    INTO actual_type
    FROM employees
    WHERE employee_id = parent_id;

    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    IF TG_TABLE_NAME = 'permanent_employees' THEN
        expected_type := 'PERMANENT';

    ELSIF TG_TABLE_NAME = 'contract_employees' THEN
        expected_type := 'CONTRACT';

    ELSIF TG_TABLE_NAME = 'intern_employees' THEN
        expected_type := 'INTERN';

    ELSIF TG_TABLE_NAME = 'senior_employees' THEN
        SELECT employment_type
        INTO expected_type
        FROM employees
        WHERE employee_id = parent_id;
    END IF;

    IF actual_type <> expected_type THEN
        RAISE EXCEPTION
            'Employee % has incompatible employment type %',
            parent_id,
            actual_type;
    END IF;

    IF TG_TABLE_NAME <> 'senior_employees' THEN

        SELECT
            (EXISTS (
                SELECT 1 FROM permanent_employees
                WHERE employee_id = parent_id
            ))::INTEGER
            +
            (EXISTS (
                SELECT 1 FROM contract_employees
                WHERE employee_id = parent_id
            ))::INTEGER
            +
            (EXISTS (
                SELECT 1 FROM intern_employees
                WHERE employee_id = parent_id
            ))::INTEGER
        INTO subtype_count;

        IF subtype_count > 1 THEN
            RAISE EXCEPTION
                'Employee % cannot have multiple primary subtypes',
                parent_id;
        END IF;

    ELSE
        IF NOT EXISTS (
            SELECT 1
            FROM permanent_employees
            WHERE employee_id = parent_id
        ) THEN
            RAISE EXCEPTION
                'Senior employee % must be permanent',
                parent_id;
        END IF;
    END IF;

    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_permanent_subtype_integrity
AFTER INSERT OR UPDATE OR DELETE
ON permanent_employees
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION validate_employee_subtype();

CREATE CONSTRAINT TRIGGER trg_contract_subtype_integrity
AFTER INSERT OR UPDATE OR DELETE
ON contract_employees
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION validate_employee_subtype();

CREATE CONSTRAINT TRIGGER trg_intern_subtype_integrity
AFTER INSERT OR UPDATE OR DELETE
ON intern_employees
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION validate_employee_subtype();

CREATE CONSTRAINT TRIGGER trg_senior_subtype_integrity
AFTER INSERT OR UPDATE OR DELETE
ON senior_employees
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION validate_employee_subtype();

-- ------------------------------------------------------------
-- 8. PAYROLL POLICY
-- ------------------------------------------------------------

CREATE TABLE payroll_policies (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    policy_name VARCHAR(100) NOT NULL UNIQUE,

    deduction_rate NUMERIC(5,4) NOT NULL,

    active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CHECK (deduction_rate BETWEEN 0 AND 1)
);

CREATE UNIQUE INDEX idx_one_active_policy
    ON payroll_policies(active)
    WHERE active = TRUE;

-- ------------------------------------------------------------
-- 9. PAYROLL TRANSACTION RECORDS
-- ------------------------------------------------------------

CREATE TABLE payroll_runs (
    payroll_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    employee_id BIGINT NOT NULL
        REFERENCES employees(employee_id),

    policy_id BIGINT NOT NULL
        REFERENCES payroll_policies(policy_id),

    gross_salary NUMERIC(14,2) NOT NULL,

    deductions NUMERIC(14,2) NOT NULL,

    net_salary NUMERIC(14,2) NOT NULL,

    status payroll_status NOT NULL DEFAULT 'PENDING',

    processed_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CHECK (gross_salary >= 0),

    CHECK (deductions >= 0),

    CHECK (net_salary >= 0),

    CHECK (net_salary = gross_salary - deductions)
);

CREATE INDEX idx_payroll_employee_date
    ON payroll_runs(employee_id, created_at DESC);

CREATE INDEX idx_payroll_status
    ON payroll_runs(status, created_at);

-- ------------------------------------------------------------
-- 10. PAYROLL CALCULATION FUNCTION
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION calculate_employee_salary(
    p_employee_id BIGINT
)
RETURNS NUMERIC(14,2)
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    employee_kind employment_type;
    result NUMERIC(14,2);
BEGIN
    SELECT employment_type
    INTO employee_kind
    FROM employees
    WHERE employee_id = p_employee_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Employee % does not exist',
            p_employee_id;
    END IF;

    CASE employee_kind

        WHEN 'PERMANENT' THEN

            SELECT
                p.monthly_salary
                + p.annual_bonus / 12
                + COALESCE(s.leadership_allowance, 0)
            INTO result
            FROM permanent_employees p
            LEFT JOIN senior_employees s
                ON s.employee_id = p.employee_id
            WHERE p.employee_id = p_employee_id;

        WHEN 'CONTRACT' THEN

            SELECT hourly_rate * monthly_hours
            INTO result
            FROM contract_employees
            WHERE employee_id = p_employee_id;

        WHEN 'INTERN' THEN

            SELECT monthly_stipend
            INTO result
            FROM intern_employees
            WHERE employee_id = p_employee_id;

    END CASE;

    IF result IS NULL THEN
        RAISE EXCEPTION
            'Employee % has incomplete subtype data',
            p_employee_id;
    END IF;

    RETURN result;
END;
$$;

-- ------------------------------------------------------------
-- 11. PAYROLL PROCESSING FUNCTION
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION process_employee_payroll(
    p_employee_id BIGINT
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    employee_record employees%ROWTYPE;
    policy_record payroll_policies%ROWTYPE;

    gross NUMERIC(14,2);
    deductions NUMERIC(14,2);
    net NUMERIC(14,2);

    generated_id BIGINT;
BEGIN
    SELECT *
    INTO employee_record
    FROM employees
    WHERE employee_id = p_employee_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Employee % not found',
            p_employee_id;
    END IF;

    IF employee_record.status <> 'ACTIVE' THEN
        RAISE EXCEPTION
            'Inactive employee % cannot be processed',
            p_employee_id;
    END IF;

    SELECT *
    INTO policy_record
    FROM payroll_policies
    WHERE active = TRUE
    FOR SHARE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No active payroll policy exists';
    END IF;

    gross := calculate_employee_salary(p_employee_id);

    deductions := ROUND(
        gross * policy_record.deduction_rate,
        2
    );

    net := gross - deductions;

    INSERT INTO payroll_runs (
        employee_id,
        policy_id,
        gross_salary,
        deductions,
        net_salary,
        status,
        processed_at
    )
    VALUES (
        p_employee_id,
        policy_record.policy_id,
        gross,
        deductions,
        net,
        'PROCESSED',
        CURRENT_TIMESTAMP
    )
    RETURNING payroll_id INTO generated_id;

    RETURN generated_id;
END;
$$;

