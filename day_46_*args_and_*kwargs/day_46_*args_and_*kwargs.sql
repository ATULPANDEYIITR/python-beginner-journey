-- A policy audit query identifies required checks that have not passed for
-- the current source commit.
SELECT
    pr.pull_request_number,
    definition.check_name,
    latest.state AS latest_state
FROM pull_requests pr
JOIN branch_protection_policies policy
  ON policy.repository_id = pr.repository_id
 AND policy.branch_id = pr.target_branch_id
JOIN policy_required_checks required
  ON required.policy_id = policy.policy_id
JOIN status_check_definitions definition
  ON definition.check_definition_id = required.check_definition_id
LEFT JOIN LATERAL (
    SELECT scr.state
    FROM status_check_runs scr
    WHERE scr.pull_request_id = pr.pull_request_id
      AND scr.check_definition_id = definition.check_definition_id
      AND scr.commit_sha = pr.head_sha
    ORDER BY scr.started_at DESC, scr.check_run_id DESC
    LIMIT 1
) latest ON TRUE
WHERE latest.state IS DISTINCT FROM 'passed';

-- Direct-push authorization is separate from merge eligibility.
SELECT
    member.username,
    member.role,
    policy.branch_id,
    (
        NOT policy.restrict_direct_pushes
        OR EXISTS (
            SELECT 1
            FROM protected_branch_pushers pusher
            WHERE pusher.policy_id = policy.policy_id
              AND pusher.username = member.username
        )
    ) AS direct_push_allowed,
    policy.allow_force_push,
    policy.allow_deletion,
    policy.allow_administrator_bypass
FROM repository_members member
JOIN branch_protection_policies policy
  ON policy.repository_id = member.repository_id
WHERE member.repository_id = 1
ORDER BY member.username;

