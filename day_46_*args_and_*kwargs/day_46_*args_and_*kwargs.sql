-- PostgreSQL repository governance model.
-- Pull request lifecycle, review discussions, approvals, status checks,
-- and branch protection are modeled as separate but related concerns.

BEGIN;

CREATE SCHEMA IF NOT EXISTS repository_governance;
SET search_path TO repository_governance, public;

CREATE TABLE IF NOT EXISTS repositories (
    repository_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_name TEXT NOT NULL UNIQUE,
    default_branch TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (length(trim(repository_name)) > 0),
    CHECK (length(trim(default_branch)) > 0)
);

CREATE TABLE IF NOT EXISTS repository_branches (
    branch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    branch_name TEXT NOT NULL,
    head_sha TEXT NOT NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (repository_id, branch_name),
    CHECK (length(trim(branch_name)) > 0),
    CHECK (length(trim(head_sha)) > 0)
);

CREATE TABLE IF NOT EXISTS repository_members (
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    username TEXT NOT NULL,
    role TEXT NOT NULL CHECK (
        role IN ('read', 'write', 'maintain', 'admin')
    ),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (repository_id, username),
    CHECK (length(trim(username)) > 0)
);

CREATE TABLE IF NOT EXISTS pull_requests (
    pull_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    pull_request_number INTEGER NOT NULL,
    title TEXT NOT NULL,
    author TEXT NOT NULL,
    source_branch_id BIGINT NOT NULL REFERENCES repository_branches(branch_id),
    target_branch_id BIGINT NOT NULL REFERENCES repository_branches(branch_id),
    head_sha TEXT NOT NULL,
    base_sha TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'open'
        CHECK (state IN ('open', 'closed', 'merged')),
    is_draft BOOLEAN NOT NULL DEFAULT TRUE,
    has_merge_conflicts BOOLEAN NOT NULL DEFAULT FALSE,
    has_linear_history BOOLEAN NOT NULL DEFAULT TRUE,
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    merged_at TIMESTAMPTZ,
    UNIQUE (repository_id, pull_request_number),
    CHECK (pull_request_number > 0),
    CHECK (length(trim(title)) > 0),
    CHECK (length(trim(author)) > 0),
    CHECK (length(trim(head_sha)) > 0),
    CHECK (length(trim(base_sha)) > 0),
    CHECK (source_branch_id <> target_branch_id),
    CHECK (
        (state = 'merged' AND merged_at IS NOT NULL)
        OR (state <> 'merged' AND merged_at IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS pull_request_commits (
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id)
        ON DELETE CASCADE,
    commit_sha TEXT NOT NULL,
    commit_message TEXT NOT NULL,
    author TEXT NOT NULL,
    committed_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (pull_request_id, commit_sha),
    CHECK (length(trim(commit_sha)) > 0),
    CHECK (length(trim(commit_message)) > 0)
);

CREATE TABLE IF NOT EXISTS requested_reviewers (
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id)
        ON DELETE CASCADE,
    reviewer TEXT NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (pull_request_id, reviewer),
    CHECK (length(trim(reviewer)) > 0)
);

CREATE TABLE IF NOT EXISTS reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id)
        ON DELETE CASCADE,
    reviewer TEXT NOT NULL,
    state TEXT NOT NULL CHECK (
        state IN ('approved', 'changes_requested', 'commented', 'dismissed')
    ),
    commit_sha TEXT NOT NULL,
    review_body TEXT,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dismissed_at TIMESTAMPTZ,
    CHECK (
        (state = 'dismissed' AND dismissed_at IS NOT NULL)
        OR (state <> 'dismissed' AND dismissed_at IS NULL)
    ),
    CHECK (length(trim(reviewer)) > 0),
    CHECK (length(trim(commit_sha)) > 0)
);

CREATE TABLE IF NOT EXISTS review_comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT REFERENCES reviews(review_id) ON DELETE CASCADE,
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id)
        ON DELETE CASCADE,
    author TEXT NOT NULL,
    file_path TEXT,
    line_number INTEGER,
    body TEXT NOT NULL,
    is_inline BOOLEAN NOT NULL DEFAULT FALSE,
    is_resolved BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    CHECK (length(trim(author)) > 0),
    CHECK (length(trim(body)) > 0),
    CHECK (line_number IS NULL OR line_number > 0),
    CHECK (
        (is_inline AND file_path IS NOT NULL AND line_number IS NOT NULL)
        OR NOT is_inline
    ),
    CHECK (
        (is_resolved AND resolved_at IS NOT NULL)
        OR (NOT is_resolved AND resolved_at IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS status_check_definitions (
    check_definition_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    check_name TEXT NOT NULL,
    UNIQUE (repository_id, check_name),
    CHECK (length(trim(check_name)) > 0)
);

CREATE TABLE IF NOT EXISTS status_check_runs (
    check_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_definition_id BIGINT NOT NULL
        REFERENCES status_check_definitions(check_definition_id)
        ON DELETE CASCADE,
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id)
        ON DELETE CASCADE,
    commit_sha TEXT NOT NULL,
    state TEXT NOT NULL CHECK (state IN ('pending', 'passed', 'failed')),
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CHECK (length(trim(commit_sha)) > 0),
    CHECK (
        (state = 'pending' AND completed_at IS NULL)
        OR (state <> 'pending' AND completed_at IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS branch_protection_policies (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    branch_id BIGINT NOT NULL REFERENCES repository_branches(branch_id)
        ON DELETE CASCADE,
    required_approvals INTEGER NOT NULL DEFAULT 1,
    require_resolved_conversations BOOLEAN NOT NULL DEFAULT TRUE,
    dismiss_stale_approvals BOOLEAN NOT NULL DEFAULT TRUE,
    require_linear_history BOOLEAN NOT NULL DEFAULT FALSE,
    restrict_direct_pushes BOOLEAN NOT NULL DEFAULT TRUE,
    allow_force_push BOOLEAN NOT NULL DEFAULT FALSE,
    allow_deletion BOOLEAN NOT NULL DEFAULT FALSE,
    allow_administrator_bypass BOOLEAN NOT NULL DEFAULT FALSE,
    require_signed_commits BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (repository_id, branch_id),
    CHECK (required_approvals >= 0)
);

CREATE TABLE IF NOT EXISTS policy_required_checks (
    policy_id BIGINT NOT NULL REFERENCES branch_protection_policies(policy_id)
        ON DELETE CASCADE,
    check_definition_id BIGINT NOT NULL
        REFERENCES status_check_definitions(check_definition_id)
        ON DELETE CASCADE,
    PRIMARY KEY (policy_id, check_definition_id)
);

CREATE TABLE IF NOT EXISTS protected_branch_pushers (
    policy_id BIGINT NOT NULL REFERENCES branch_protection_policies(policy_id)
        ON DELETE CASCADE,
    username TEXT NOT NULL,
    PRIMARY KEY (policy_id, username)
);

CREATE INDEX IF NOT EXISTS idx_pull_requests_target_state
    ON pull_requests(target_branch_id, state);

CREATE INDEX IF NOT EXISTS idx_reviews_current_head
    ON reviews(pull_request_id, commit_sha, submitted_at DESC);

CREATE INDEX IF NOT EXISTS idx_review_comments_unresolved
    ON review_comments(pull_request_id)
    WHERE is_resolved = FALSE;

CREATE INDEX IF NOT EXISTS idx_status_check_head
    ON status_check_runs(pull_request_id, commit_sha, check_definition_id);

CREATE OR REPLACE FUNCTION enforce_review_author_and_eligibility()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    pr_author TEXT;
    current_head TEXT;
    repo_id BIGINT;
    reviewer_is_active BOOLEAN;
BEGIN
    SELECT author, head_sha, repository_id
      INTO pr_author, current_head, repo_id
      FROM pull_requests
     WHERE pull_request_id = NEW.pull_request_id
       AND state = 'open';

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Reviews require an open pull request';
    END IF;

    IF NEW.reviewer = pr_author THEN
        RAISE EXCEPTION 'Pull request authors cannot review their own changes';
    END IF;

    IF NEW.commit_sha <> current_head THEN
        RAISE EXCEPTION 'Review commit does not match current pull request head';
    END IF;

    SELECT active
      INTO reviewer_is_active
      FROM repository_members
     WHERE repository_id = repo_id
       AND username = NEW.reviewer
       AND role IN ('write', 'maintain', 'admin');

    IF reviewer_is_active IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'Reviewer is not an active eligible repository member';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_review_author_eligibility ON reviews;

CREATE TRIGGER trg_review_author_eligibility
BEFORE INSERT OR UPDATE OF pull_request_id, reviewer, commit_sha, state
ON reviews
FOR EACH ROW
WHEN (NEW.state <> 'dismissed')
EXECUTE FUNCTION enforce_review_author_and_eligibility();

CREATE OR REPLACE FUNCTION enforce_comment_consistency()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    review_pr_id BIGINT;
BEGIN
    IF NEW.review_id IS NOT NULL THEN
        SELECT pull_request_id
          INTO review_pr_id
          FROM reviews
         WHERE review_id = NEW.review_id;

        IF review_pr_id IS DISTINCT FROM NEW.pull_request_id THEN
            RAISE EXCEPTION 'Comment and review must belong to the same pull request';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_comment_consistency ON review_comments;

CREATE TRIGGER trg_comment_consistency
BEFORE INSERT OR UPDATE OF review_id, pull_request_id
ON review_comments
FOR EACH ROW
EXECUTE FUNCTION enforce_comment_consistency();

-- Evaluate current approvals, policy requirements, and status checks together.
-- The latest review by each reviewer is considered for the current head SHA.
CREATE OR REPLACE VIEW pull_request_merge_eligibility AS
WITH latest_reviews AS (
    SELECT DISTINCT ON (r.pull_request_id, r.reviewer)
        r.pull_request_id,
        r.reviewer,
        r.state,
        r.commit_sha
    FROM reviews r
    JOIN pull_requests pr ON pr.pull_request_id = r.pull_request_id
    WHERE r.state <> 'dismissed'
      AND r.commit_sha = pr.head_sha
    ORDER BY r.pull_request_id, r.reviewer, r.submitted_at DESC, r.review_id DESC
),
review_totals AS (
    SELECT
        pull_request_id,
        COUNT(*) FILTER (WHERE state = 'approved') AS approval_count,
        BOOL_OR(state = 'changes_requested') AS changes_requested
    FROM latest_reviews
    GROUP BY pull_request_id
),
conversation_totals AS (
    SELECT
        pull_request_id,
        COUNT(*) FILTER (WHERE NOT is_resolved) AS unresolved_count
    FROM review_comments
    GROUP BY pull_request_id
),
check_totals AS (
    SELECT
        p.pull_request_id,
        COUNT(*) FILTER (
            WHERE latest_run.state = 'passed'
        ) AS passed_required_checks,
        COUNT(*) FILTER (
            WHERE latest_run.state IS DISTINCT FROM 'passed'
        ) AS unsatisfied_required_checks
    FROM pull_requests p
    JOIN branch_protection_policies policy
      ON policy.branch_id = p.target_branch_id
     AND policy.repository_id = p.repository_id
    LEFT JOIN policy_required_checks required
      ON required.policy_id = policy.policy_id
    LEFT JOIN LATERAL (
        SELECT scr.state
        FROM status_check_runs scr
        WHERE scr.pull_request_id = p.pull_request_id
          AND scr.check_definition_id = required.check_definition_id
          AND scr.commit_sha = p.head_sha
        ORDER BY scr.started_at DESC, scr.check_run_id DESC
        LIMIT 1
    ) latest_run ON TRUE
    GROUP BY p.pull_request_id
)
SELECT
    p.pull_request_id,
    p.repository_id,
    p.pull_request_number,
    p.title,
    p.state,
    p.is_draft,
    p.head_sha,
    COALESCE(rt.approval_count, 0) AS current_approvals,
    policy.required_approvals,
    COALESCE(rt.changes_requested, FALSE) AS changes_requested,
    COALESCE(ct.unresolved_count, 0) AS unresolved_conversations,
    COALESCE(cht.unsatisfied_required_checks, 0) AS unsatisfied_required_checks,
    p.has_merge_conflicts,
    p.has_linear_history,
    policy.require_linear_history,
    (
        p.state = 'open'
        AND NOT p.is_draft
        AND NOT p.has_merge_conflicts
        AND COALESCE(rt.approval_count, 0) >= policy.required_approvals
        AND NOT COALESCE(rt.changes_requested, FALSE)
        AND (
            NOT policy.require_resolved_conversations
            OR COALESCE(ct.unresolved_count, 0) = 0
        )
        AND (
            NOT policy.require_linear_history
            OR p.has_linear_history
        )
        AND COALESCE(cht.unsatisfied_required_checks, 0) = 0
    ) AS merge_eligible
FROM pull_requests p
JOIN branch_protection_policies policy
  ON policy.repository_id = p.repository_id
 AND policy.branch_id = p.target_branch_id
LEFT JOIN review_totals rt ON rt.pull_request_id = p.pull_request_id
LEFT JOIN conversation_totals ct ON ct.pull_request_id = p.pull_request_id
LEFT JOIN check_totals cht ON cht.pull_request_id = p.pull_request_id;

